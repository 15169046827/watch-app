CREATE TABLE plans (id TEXT PRIMARY KEY NOT NULL, version INTEGER NOT NULL CHECK(version > 0), body TEXT NOT NULL);
CREATE TABLE instances (id TEXT PRIMARY KEY NOT NULL, plan_id TEXT NOT NULL, start_ms INTEGER NOT NULL, body TEXT NOT NULL);
CREATE INDEX instances_start ON instances(start_ms);
CREATE TABLE events (id TEXT PRIMARY KEY NOT NULL, instance_id TEXT NOT NULL, logical INTEGER NOT NULL, body TEXT NOT NULL);
CREATE INDEX events_instance ON events(instance_id);
CREATE TABLE meta (key TEXT PRIMARY KEY NOT NULL, value TEXT NOT NULL);
CREATE TABLE outbox (id TEXT PRIMARY KEY NOT NULL, revision INTEGER NOT NULL, body BLOB NOT NULL);
CREATE TABLE inbox (id TEXT PRIMARY KEY NOT NULL, digest TEXT NOT NULL);
